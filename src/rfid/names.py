"""Сравнение ФИО.

Связь «карта → студент» держится на совпадении ФИО из списка группы,
поэтому одно и то же правило нужно и базе, и разбору таблиц. Отдельный
модуль без зависимостей: базе незачем тянуть за собой openpyxl.
"""

from __future__ import annotations


def normalize_name(name: str) -> str:
    """Для сравнения ФИО: регистр, ё и лишние пробелы значения не имеют."""
    return " ".join(name.replace("ё", "е").replace("Ё", "Е").split()).casefold()
